#include <stdio.h>
int main()
{
    char *a[] = {"    *", "   * *", "  *   *", " *     *", "*********",
                 "    *", "   ***", "  *****", " *******", "*********",
                 "*********", " *******", "  *****", "   ***", "    *"};
    int n;
    if (scanf("%d", &n) != 1)
    {
        return 0;
    }

    for (int i = 0; i < 5; ++i)
    {
        printf("%s", a[i + 5 * (n - 1)]);
        printf("\n");
    }
    return 0;
}